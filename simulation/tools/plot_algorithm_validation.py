#!/usr/bin/env python3
"""Plot measured first-mission trajectories from a local algorithm comparison JSON.

Usage: python3 simulation/tools/plot_algorithm_validation.py INPUT_JSON OUTPUT_PNG
INPUT_JSON is generated by the session analysis; plotting never connects to a UAV.
"""
import json
from pathlib import Path
import sys

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt

if len(sys.argv) != 3:
    raise SystemExit(f'usage: {sys.argv[0]} comparison.json output.png')
cases = json.loads(Path(sys.argv[1]).read_text())
colors = {'baseline': '#c45a4d', 'limited': '#4987ae', 'reference': '#24784a'}
labels = {'baseline': 'PX4 defaults', 'limited': 'Slow 0.5 m/s, hover 0.5',
          'reference': 'Selected slow, hover 0.74'}
fig, axes = plt.subplots(2, 2, figsize=(11, 7))
for case in cases:
    traces = case['cycles'][0]['traces']
    t0 = traces[0]['t_s']
    t = [p['t_s'] - t0 for p in traces]
    c = colors[case['case']]
    label = labels[case['case']]
    axes[0, 0].plot([p['east_m'] for p in traces], [p['north_m'] for p in traces],
                    label=label, color=c, lw=1.4)
    axes[0, 1].plot(t, [p['height_m'] for p in traces], color=c, lw=1.3)
    axes[1, 0].plot(t, [p['horizontal_speed_m_s'] for p in traces], color=c, lw=1.3)
    axes[1, 1].plot(t, [p['xy_error_m'] for p in traces], color=c, lw=1.3)
for ax in axes.flat:
    ax.grid(alpha=.25)
axes[0, 0].scatter([0, 1], [0, 1], marker='x', color='black', zorder=5)
axes[0, 0].set(xlabel='East from launch (m)', ylabel='North from launch (m)', title='Gazebo model XY path')
axes[0, 0].axis('equal')
axes[0, 1].set(xlabel='Time after first pose (s)', ylabel='Height above launch (m)', title='Gazebo model height')
axes[1, 0].set(xlabel='Time after first pose (s)', ylabel='Estimated XY speed (m/s)', title='PX4 local velocity')
axes[1, 1].set(xlabel='Time after first pose (s)', ylabel='Distance to current target (m)', title='Gazebo model XY target error')
fig.suptitle('X500 Classic HITL: first complete mission in each configuration (2026-10-26)')
fig.legend(*axes[0, 0].get_legend_handles_labels(), loc='lower center', ncol=3,
           bbox_to_anchor=(.5, .01), frameon=False)
fig.subplots_adjust(bottom=.14, top=.89, hspace=.43, wspace=.23)
output = Path(sys.argv[2])
output.parent.mkdir(parents=True, exist_ok=True)
fig.savefig(output, dpi=170)
print(output)
